CREATE TABLE user_profile_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    image_url VARCHAR(255) NOT NULL,
    order_index INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_profile_images_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE TABLE pet_profile_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id BIGINT NOT NULL,
    image_url VARCHAR(255) NOT NULL,
    order_index INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pet_profile_images_pet FOREIGN KEY (pet_id) REFERENCES pets (id)
);
CREATE INDEX idx_user_profile_images_user_id ON user_profile_images (user_id);
CREATE INDEX idx_pet_profile_images_pet_id ON pet_profile_images (pet_id);